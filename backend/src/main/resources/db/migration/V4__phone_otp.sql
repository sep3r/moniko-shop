-- ایمیل دیگر اجباری نیست (کاربران جدید فقط شماره دارند)
ALTER TABLE users ALTER COLUMN email DROP NOT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS phone_verified BOOLEAN NOT NULL DEFAULT FALSE;

-- شماره‌های قدیمی (ارقام فارسی، +98، 0098، بدون صفر) به شکل 09xxxxxxxxx درمی‌آیند.
-- شماره‌هایی که موبایل معتبر نیستند دست‌نخورده می‌مانند.
UPDATE users SET phone = NULL WHERE phone IS NOT NULL AND btrim(phone) = '';

UPDATE users u
SET phone = n.p
FROM (
    SELECT id,
           CASE
               WHEN d ~ '^09[0-9]{9}$'      THEN d
               WHEN d ~ '^0098[0-9]{10}$'   THEN '0' || substr(d, 5)
               WHEN d ~ '^98[0-9]{10}$'     THEN '0' || substr(d, 3)
               WHEN d ~ '^9[0-9]{9}$'       THEN '0' || d
               ELSE NULL
           END AS p
    FROM (
        SELECT id,
               regexp_replace(
                   translate(phone, '۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩', '01234567890123456789'),
                   '[^0-9]', '', 'g') AS d
        FROM users
        WHERE phone IS NOT NULL
    ) s
) n
WHERE u.id = n.id AND n.p IS NOT NULL;

-- اگر چند حساب یک شماره‌ی معتبر دارند، فقط قدیمی‌ترین نگهش می‌دارد
UPDATE users SET phone = NULL
WHERE id IN (
    SELECT id FROM (
        SELECT id, row_number() OVER (PARTITION BY phone ORDER BY id) AS rn
        FROM users
        WHERE phone ~ '^09[0-9]{9}$'
    ) t WHERE rn > 1
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_users_phone ON users (phone) WHERE phone ~ '^09[0-9]{9}$';

-- کدهای پیامکی (فقط HMAC کد ذخیره می‌شود)
CREATE TABLE IF NOT EXISTS otp_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone       VARCHAR(20) NOT NULL,
    purpose     VARCHAR(20) NOT NULL,
    code_hash   VARCHAR(64) NOT NULL,
    attempts    INTEGER NOT NULL DEFAULT 0,
    consumed    BOOLEAN NOT NULL DEFAULT FALSE,
    ip          VARCHAR(64),
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_otp_codes_phone_created ON otp_codes (phone, created_at);
CREATE INDEX IF NOT EXISTS idx_otp_codes_created ON otp_codes (created_at);

-- بازیابی رمز با لینک ایمیل حذف شد (جایگزین: OTP پیامکی)
DROP TABLE IF EXISTS password_reset_tokens;
