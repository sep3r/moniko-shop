CREATE TABLE IF NOT EXISTS visit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_date  DATE NOT NULL,
    visitor_id  VARCHAR(36) NOT NULL,
    user_id     BIGINT,
    ip          VARCHAR(64) NOT NULL,
    user_agent  VARCHAR(255),
    first_seen  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_seen   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_visit_log UNIQUE (visit_date, visitor_id, ip)
);
CREATE INDEX IF NOT EXISTS idx_visit_log_date ON visit_log (visit_date);
CREATE INDEX IF NOT EXISTS idx_visit_log_ip   ON visit_log (ip);
CREATE INDEX IF NOT EXISTS idx_visit_log_user ON visit_log (user_id);

CREATE TABLE IF NOT EXISTS security_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    event_type  VARCHAR(40) NOT NULL,
    user_id     BIGINT,
    email       VARCHAR(100),
    ip          VARCHAR(64),
    user_agent  VARCHAR(255),
    details     VARCHAR(500)
);
CREATE INDEX IF NOT EXISTS idx_security_event_created ON security_event (created_at);
CREATE INDEX IF NOT EXISTS idx_security_event_type    ON security_event (event_type);
CREATE INDEX IF NOT EXISTS idx_security_event_ip      ON security_event (ip);
CREATE INDEX IF NOT EXISTS idx_security_event_email   ON security_event (email);
